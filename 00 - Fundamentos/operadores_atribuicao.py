saldo = 500
print(saldo)

# Atribuição simples
saldo = 200
print(saldo)

# Atribuições compostas: aplicam operação e reatribuem
# Adição
saldo += 10
print(saldo)

# Subtração
saldo -= 5
print(saldo)

# Divisão inteira (floor)
saldo //= 2
print(saldo)

# Divisão real
saldo /= 2
print(saldo)

# Multiplicação
saldo *= 10
print(saldo)

# Módulo (resto)
saldo %= 4
print(saldo)

# Exponenciação
saldo **= 2
print(saldo)
